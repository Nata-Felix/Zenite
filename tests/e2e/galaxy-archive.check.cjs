// Interface e serviços reais; somente os seletores de arquivo nativos são simulados.
const { app, dialog, session } = require('electron');
const { mkdirSync, mkdtempSync, writeFileSync, readFileSync, existsSync } = require('node:fs');
const { join } = require('node:path');
const assert = require('node:assert/strict');
const root = process.cwd(), dir = join(root, 'out/galaxy-archive-qa');
mkdirSync(dir, { recursive: true });
const profile = mkdtempSync(join(dir, 'profile-')), project = join(profile, 'projeto'), parallel = join(profile, 'paralelo'), home = join(profile, 'home');
for (const path of [project, parallel, join(home, '.agents/skills'), join(profile, 'notes'), join(profile, 'media'), join(profile, 'workspaces')]) mkdirSync(path, { recursive: true });
process.env.ZENITE_DATA_DIR = profile;
require('node:os').homedir = () => home;
writeFileSync(join(project, '.env'), 'QA_TOKEN=segredo-galaxia-visual');
writeFileSync(join(parallel, '.env'), 'QA_TOKEN=segredo-universo-visual');
writeFileSync(join(project, 'app.txt'), 'Projeto exportado pela interface');
writeFileSync(join(parallel, 'app.txt'), 'Universo exportado pela interface');
writeFileSync(join(profile, 'notes/nota.md'), '# Conteúdo incluído no pacote');
// PNG 1x1, só para testar o transporte de mídia.
writeFileSync(join(profile, 'media/pixel.png'), Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jA1sAAAAASUVORK5CYII=', 'base64'));
const element = (id, kind, x, extra = {}) => ({ id, kind, x, y: 160, width: 360, height: 260, element: { id, kind, title: id === 'nota' ? 'Plano da galáxia' : 'Imagem', ...extra } });
writeFileSync(join(profile, 'workspaces/index.json'), JSON.stringify({ version: 1, activeId: 'qa', workspaces: [{ id: 'qa', name: 'Galáxia de demonstração', dir: project, universes: [{ id: 'paralelo', name: 'Experimento', path: parallel, worktree: parallel, isolated: true, branch: 'codex/teste' }] }], settings: { confirmQuit: false, agentPermissions: 'sandbox', agentGuide: false, notifyDone: false } }));
writeFileSync(join(profile, 'workspaces/qa.json'), JSON.stringify({ version: 1, nodes: [element('nota', 'note', 30), element('imagem', 'image', 500, { file: 'pixel.png' })], edges: [{ id: 'link', source: 'nota', target: 'imagem' }], viewport: { x: 30, y: 10, zoom: .8 } }));
writeFileSync(join(profile, 'workspaces/paralelo.json'), JSON.stringify({ version: 1, nodes: [], edges: [], viewport: { x: 0, y: 0, zoom: 1 } }));
const seed = join(dir, 'seed.cjs'); writeFileSync(seed, "localStorage.setItem('o.summaryView','false');");
app.whenReady().then(() => session.defaultSession.registerPreloadScript({ type: 'frame', filePath: seed }));
let savePath = join(profile, 'pacote.zenite-galaxia'), pickPath = savePath;
dialog.showSaveDialog = async () => ({ canceled: false, filePath: savePath });
dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [pickPath] });
const errors = [], delay = ms => new Promise(r => setTimeout(r, ms));
let win;
const js = code => win.webContents.executeJavaScript(code, true);
const until = async (code, label) => { for (let i = 0; i < 100; i++) { if (await js(`!!(${code})`)) { console.log('OK: ' + label); return; } await delay(80); } throw Error('Timeout: ' + label); };
const click = async selector => { await js(`document.querySelector(${JSON.stringify(selector)}).click()`); await delay(250); };
const screenshot = async name => writeFileSync(join(dir, name + '.png'), (await win.webContents.capturePage()).toPNG());
const ready = new Promise(resolve => app.once('browser-window-created', (_e, w) => { w.webContents.on('console-message', event => { if (event.level === 'error' && !event.message.includes('ResizeObserver')) errors.push(event.message); }); w.webContents.once('did-finish-load', () => resolve(w)); }));
app.whenReady().then(async () => {
  try {
    win = await ready; win.show();
    await until("document.querySelectorAll('.react-flow__node').length===2", 'galáxia real com nota, imagem e universo');
    await click('button[aria-label="Exportar galáxia Galáxia de demonstração"]');
    await until("document.querySelector('.galaxy-archive-dialog')", 'exportar galáxia na barra lateral');
    assert.equal(await js("document.querySelectorAll('.galaxy-archive-option input').length"), 3);
    assert.equal(await js("document.querySelectorAll('.galaxy-archive-option input')[2].checked"), false, '.env começa desmarcado');
    await screenshot('01-exportar-opcoes');
    await click('.galaxy-archive-dialog .primary');
    await until("document.querySelector('.galaxy-archive-dialog [role=status]')", 'exportação sem .env concluída');
    assert.ok(existsSync(savePath)); assert.ok(!readFileSync(savePath).includes(Buffer.from('segredo-galaxia-visual')));
    await click('.galaxy-archive-dialog .ghost');
    await click('button[aria-label="Importar galáxia"]');
    await until("document.querySelector('.galaxy-archive-dialog')", 'importação mostra o resumo do pacote');
    assert.equal(await js("document.querySelectorAll('.galaxy-archive-option input')[2].disabled"), true, '.env ausente não pode ser selecionado');
    await screenshot('02-importar-resumo');
    await click('.galaxy-archive-dialog .primary');
    await until("document.querySelector('.galaxy-archive-dialog [role=status]')", 'galáxia importada como nova cópia');
    let index = await js('window.o.workspaces.list()');
    assert.equal(index.workspaces.length, 2); assert.equal(index.activeId, 'qa');
    let imported = index.workspaces.find(w => w.id !== 'qa');
    assert.equal(imported.universes.length, 1); assert.equal(existsSync(join(imported.dir, '.env')), false);
    let state = await js(`window.o.canvas.load(${JSON.stringify(imported.id)})`);
    assert.equal(state.nodes.length, 2); assert.equal(state.edges.length, 1);
    assert.match(await js(`window.o.elements.readNote(${JSON.stringify(state.nodes.find(n => n.kind === 'note').id)})`), /Conteúdo incluído/);
    await click('.galaxy-archive-dialog .ghost');
    savePath = join(profile, 'pacote-com-env.zenite-galaxia'); pickPath = savePath;
    await click('button[aria-label="Exportar galáxia Galáxia de demonstração"]');
    await click('.galaxy-archive-option:last-child input');
    await screenshot('03-env-inclusao-explicita');
    await click('.galaxy-archive-dialog .primary'); await until("document.querySelector('.galaxy-archive-dialog [role=status]')", 'exportação com .env explícito');
    assert.ok(readFileSync(savePath).includes(Buffer.from('segredo-galaxia-visual')));
    await click('.galaxy-archive-dialog .ghost'); await click('button[aria-label="Importar galáxia"]');
    assert.equal(await js("document.querySelectorAll('.galaxy-archive-option input')[2].checked"), false, 'importação exige nova escolha de .env');
    await click('.galaxy-archive-option:last-child input'); await click('.galaxy-archive-dialog .primary');
    await until("document.querySelector('.galaxy-archive-dialog [role=status]')", 'importação do .env autorizada');
    index = await js('window.o.workspaces.list()'); imported = index.workspaces.at(-1);
    assert.equal(readFileSync(join(imported.dir, '.env'), 'utf8'), 'QA_TOKEN=segredo-galaxia-visual');
    assert.equal(readFileSync(join(imported.universes[0].path, '.env'), 'utf8'), 'QA_TOKEN=segredo-universo-visual');
    assert.equal(index.activeId, 'qa');
    await screenshot('04-importacao-concluida'); await click('.galaxy-archive-dialog .ghost');
    await click('button[aria-label="Importar galáxia"]');
    await click('.galaxy-archive-option:nth-child(1) input'); await click('.galaxy-archive-option:nth-child(2) input');
    await click('.galaxy-archive-dialog .primary');
    await until("document.querySelector('.galaxy-archive-dialog [role=status]')", 'template sem conteúdos, mídia ou .env');
    index = await js('window.o.workspaces.list()'); imported = index.workspaces.at(-1);
    state = await js(`window.o.canvas.load(${JSON.stringify(imported.id)})`);
    assert.equal(state.nodes.length, 2); assert.equal(state.edges.length, 1);
    assert.ok(!state.nodes.find(n => n.kind === 'image').element.file);
    assert.equal(await js(`window.o.elements.readNote(${JSON.stringify(state.nodes.find(n => n.kind === 'note').id)})`), '');
    assert.equal(existsSync(join(imported.dir, '.env')), false);
    await click('.galaxy-archive-dialog .ghost');
    pickPath = join(profile, 'invalido.zenite-galaxia'); writeFileSync(pickPath, 'inválido');
    await click('button[aria-label="Importar galáxia"]');
    await until("document.querySelector('[role=alertdialog]')", 'pacote inválido mostra erro legível');
    await click('[role=alertdialog] button');
    assert.deepEqual(errors, []);
    writeFileSync(join(dir, 'resultado.json'), JSON.stringify({ ok: true, profile, importedGalaxies: 3, options: ['contents', 'media', 'env'], errors }, null, 2));
    console.log('PASS: exportar/importar galáxias no Zênite real, com .env opcional e universos preservados');
    if (process.argv.includes('--keep-open')) return;
    win.destroy(); app.quit();
  } catch (error) { console.error(error.stack); if (win) await screenshot('erro').catch(() => {}); app.exit(1); }
});
require(join(root, 'out/main/index.js'));
